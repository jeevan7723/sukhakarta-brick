// Global language switcher helper
let currentLang = localStorage.getItem('sukhakarta_lang') || 'en';

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('sukhakarta_lang', lang);

  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;

  // Update text elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  // Update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  // Update active state on language switcher buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Update html lang attribute
  document.documentElement.lang = lang;

  // Trigger calculator recalculation so WhatsApp message generated is in current language
  if (typeof window.recalculateForLanguage === 'function') {
    window.recalculateForLanguage(lang);
  }
}
